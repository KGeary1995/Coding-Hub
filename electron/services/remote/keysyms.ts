/**
 * What a VNC key event (an X11 keysym) presses on Windows: a virtual key, or a character the input helper types with
 * the key that makes it on this keyboard layout (so shortcuts like Ctrl+C work), or as Unicode when no key does.
 */
export type KeyAction = { vk: number; extended?: boolean } | { char: number };

/** Named keys: keysym → [virtual key, extended]. */
const NAMED: Record<number, [number, boolean?]> = {
  0xff08: [0x08], 0xff09: [0x09], 0xff0d: [0x0d], 0xff13: [0x13], 0xff14: [0x91], 0xff1b: [0x1b], 0xffff: [0x2e, true],
  0xff50: [0x24, true], 0xff51: [0x25, true], 0xff52: [0x26, true], 0xff53: [0x27, true], 0xff54: [0x28, true],
  0xff55: [0x21, true], 0xff56: [0x22, true], 0xff57: [0x23, true], 0xff61: [0x2c], 0xff63: [0x2d, true], 0xff67: [0x5d, true],
  0xff7f: [0x90, true], 0xffe5: [0x14],
  0xffe1: [0xa0], 0xffe2: [0xa1], 0xffe3: [0xa2], 0xffe4: [0xa3, true], 0xffe9: [0xa4], 0xffea: [0xa5, true],
  // A Mac viewer sends ⌘ as Control itself (LinkedScreen); its Option keys come as Mode_switch and ISO_Level3_Shift.
  0xff7e: [0xa4], 0xfe03: [0xa5, true],
  // Meta and Super (the Windows key on other viewers).
  0xffe7: [0x5b, true], 0xffe8: [0x5c, true], 0xffeb: [0x5b, true], 0xffec: [0x5c, true],
  // Keypad.
  0xff8d: [0x0d, true], 0xffaa: [0x6a], 0xffab: [0x6b], 0xffad: [0x6d], 0xffae: [0x6e], 0xffaf: [0x6f, true],
  0xff95: [0x24], 0xff96: [0x25], 0xff97: [0x26], 0xff98: [0x27], 0xff99: [0x28], 0xff9a: [0x21], 0xff9b: [0x22], 0xff9c: [0x23], 0xff9e: [0x2d], 0xff9f: [0x2e],
};

export function keyAction(keysym: number): KeyAction | null {
  const named = NAMED[keysym]; if (named) return named[1] ? { vk: named[0], extended: true } : { vk: named[0] };
  if (keysym >= 0xffbe && keysym <= 0xffd5) return { vk: 0x70 + keysym - 0xffbe }; // F1–F24
  if (keysym >= 0xffb0 && keysym <= 0xffb9) return { vk: 0x60 + keysym - 0xffb0 }; // keypad digits
  if ((keysym >= 0x20 && keysym <= 0x7e) || (keysym >= 0xa0 && keysym <= 0xff)) return { char: keysym };
  if (keysym >= 0x01000100 && keysym <= 0x0110ffff) return { char: keysym - 0x01000000 };
  return null;
}
